#!/usr/bin/env python3
"""Store the generated built-in TPL losslessly, for one unpack before video starts."""

import argparse
from pathlib import Path
import struct
import zlib

MAX_BYTES = 128 * 1024


def pack(raw: bytes) -> tuple[bytes, str]:
    if not 12 <= len(raw) <= MAX_BYTES:
        raise ValueError("built-in TPL exceeds its initialization memory budget")
    magic, count, _ = struct.unpack_from(">III", raw)
    if magic != 0x0020AF30 or not 1 <= count <= 64:
        raise ValueError("not a generated built-in TPL")
    packed = zlib.compress(raw, level=9)
    if len(packed) >= len(raw) or zlib.decompress(packed) != raw:
        raise ValueError("built-in TPL did not pack losslessly into fewer bytes")
    header = ("/* Generated by pack_builtin_images.py. */\n#pragma once\n"
              f"#define UI_BUILTIN_IMAGES_BYTES {len(raw)}u\n")
    return packed, header


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("packed", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    packed, header = pack(args.source.read_bytes())
    args.packed.write_bytes(packed)
    args.header.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
