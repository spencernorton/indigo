#!/usr/bin/env python3
"""Draw the Ukrainian letters the IPL font lacks into gui/ui_font_cyrillic.inc.

The console's ANSI font has no Cyrillic, so Menu Language Ukrainian draws its
letters from a sheet of its own, laid out the way the IPL lays out its sheet:
I4 texels in 8x8 tiles, 512 texels a row, 24-texel cells 21 to a row, each
glyph drawn from the pen at its cell's left edge with its baseline 19 rows
down, one column wider than its advance (drawString overlaps neighbours by a
column). drawString swaps the sheet in as it swaps the IPL's own.

The letters come from Noto Sans (SIL Open Font License 1.1; see NOTICE), at
the weight and width that sit best beside the IPL font's Latin letters:

    https://github.com/google/fonts/raw/main/ofl/notosans/NotoSans%5Bwdth%2Cwght%5D.ttf

FreeType's rasterizer changes between versions, so the sheet is redrawn only
on purpose, never by the build.

usage: generate_cyrillic_font.py NotoSans[wdth,wght].ttf
"""
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'cube/swiss/source/gui/ui_font_cyrillic.inc'
FONT_SHA256 = 'bfb7bb691513f12e734dc346c03a03f784912432d7e3fa8e56efcf906fe86b3d'

# А..я, then the four letters Ukrainian adds to them in each case.
CODES = list(range(0x410, 0x450)) + [0x404, 0x406, 0x407, 0x454, 0x456, 0x457, 0x490, 0x491]
SIZE, WEIGHT, WIDTH = 20, 550, 80
CELL, COLUMNS, SHEET_WIDTH, BASELINE = 24, 21, 512, 19
ROWS = (len(CODES) + COLUMNS - 1) // COLUMNS
# A tile row of padding: linear filtering reads a texel past a glyph's edge.
SHEET_HEIGHT = ROWS * CELL + 8


def glyphs(path):
    font = ImageFont.truetype(str(path), SIZE)
    font.set_variation_by_axes([WEIGHT, WIDTH])
    sheet = Image.new('L', (SHEET_WIDTH, SHEET_HEIGHT))
    widths = []
    for index, code in enumerate(CODES):
        letter = chr(code)
        width = int(round(font.getlength(letter))) + 1
        if not 2 <= width <= CELL:
            raise ValueError(f'U+{code:04X} is {width} texels wide')
        cell = Image.new('L', (CELL, CELL))
        ImageDraw.Draw(cell).text((0, BASELINE), letter, font=font, fill=255, anchor='ls')
        cell = cell.crop((0, 0, width, CELL))
        sheet.paste(cell, (index % COLUMNS * CELL, index // COLUMNS * CELL))
        widths.append(width)
    return sheet, widths


def i4(sheet):
    """The sheet as GX I4: 8x8 tiles, left to right then down, two texels a byte."""
    pixels = sheet.load()
    out = bytearray()
    for ty in range(0, sheet.height, 8):
        for tx in range(0, sheet.width, 8):
            for y in range(ty, ty + 8):
                for x in range(tx, tx + 8, 2):
                    hi = (pixels[x, y] + 8) // 17
                    lo = (pixels[x + 1, y] + 8) // 17
                    out.append(hi << 4 | lo)
    return bytes(out)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = Path(sys.argv[1])
    if hashlib.sha256(path.read_bytes()).hexdigest() != FONT_SHA256:
        sys.exit(f'{path} is not the Noto Sans this sheet is drawn from')
    sheet, widths = glyphs(path)
    data = i4(sheet)
    lines = [
        '/* Generated by buildtools/ui/generate_cyrillic_font.py from Noto Sans',
        ' * (SIL Open Font License 1.1, see NOTICE); redraw it with that script. */',
        f'#define UI_FONT_CYRILLIC_GLYPHS {len(CODES)}',
        f'#define UI_FONT_CYRILLIC_CELL {CELL}',
        f'#define UI_FONT_CYRILLIC_COLUMNS {COLUMNS}',
        f'#define UI_FONT_CYRILLIC_SHEET_WIDTH {SHEET_WIDTH}',
        f'#define UI_FONT_CYRILLIC_SHEET_HEIGHT {SHEET_HEIGHT}',
        '/* Each glyph\'s code point, in the order of its cell. */',
        'static const u16 uiFontCyrillicCodes[UI_FONT_CYRILLIC_GLYPHS] = {',
    ]
    lines += ['\t' + ', '.join(f'0x{c:04x}' for c in CODES[i:i + 8]) + ',' for i in range(0, len(CODES), 8)]
    lines += ['};', 'static const u8 uiFontCyrillicWidths[UI_FONT_CYRILLIC_GLYPHS] = {']
    lines += ['\t' + ', '.join(str(w) for w in widths[i:i + 16]) + ',' for i in range(0, len(widths), 16)]
    lines += ['};', 'static u8 uiFontCyrillicSheet[UI_FONT_CYRILLIC_SHEET_WIDTH * UI_FONT_CYRILLIC_SHEET_HEIGHT / 2]',
              '\tATTRIBUTE_ALIGN(32) = {']
    lines += ['\t' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {len(CODES)} glyphs, {len(data)} bytes of sheet')


if __name__ == '__main__':
    main()
